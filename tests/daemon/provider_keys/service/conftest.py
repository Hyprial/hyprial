def bound_signer(state_dir: Path, *, bound: bool = True, enabled: bool = True,
                 expires_at: float | None = None, trusted: bool = True) -> Any:
    """A test U1 signer: generated key, test-only bound state and injected trust."""
    store = UserKey.Store(state_dir=state_dir, owner=OWNER, casdoor_sub=SUB,
                          device_uid=DEVICE, fingerprint="test-machine")
    store.ensure()
    if bound:
        path = store.root / "key.json"
        record = json.loads(path.read_text())
        record["state"] = "bound"
        path.write_text(json.dumps(record))
    deadline = time.time() + 3600 if expires_at is None else expires_at

    def trust(record: Any) -> Any:
        if not trusted:
            raise UserKey.Error("USER_KEY_UNBOUND")
        return UserKey.Trust(record.public_key, deadline, 1)

    return daemon.UserKey.Signer(store, trust=trust, enabled=enabled)


class Anchor:
    """Fake U2 verifier: verified only for the test signer's key, in the U2 Lookup shape.

    Like the real U2 ``OwnerKeyPort``, a key id with no binding document is
    unavailable (``Lookup()``), and only a key id on the revocation list is absent.
    """

    def __init__(self, signer: Any) -> None:
        status = signer.store.status()
        self.key_id = status["keyId"]
        self.public_key = status["publicKey"]
        self.state = "verified"
        self.revoked: set[str] = set()
        self.calls: list[tuple[str, str]] = []

    def lookup(self, owner: str, key_id: str) -> Lookup:
        self.calls.append((owner, key_id))
        if self.state != "verified":
            return Lookup(state=self.state)
        if key_id in self.revoked:
            return Lookup(state="absent")
        if key_id != self.key_id:
            return Lookup()
        return Lookup("verified", self.public_key, {"revocationSeq": 1}, time.time() + 3600, DEVICE, SUB)


class World:
    """One owner device: gate open, single-replica OrgFS space, registry with agent "worker"."""

    def __init__(self, tmp_path: Path) -> None:
        self.tmp = tmp_path
        self.home = tmp_path / "home"
        self.home.mkdir(mode=0o700)
        self.state = tmp_path / "state"
        self.state.mkdir(mode=0o700)
        self.settings({"owner": OWNER, "userId": SUB, "providerKeys": {"authority": "owner-keys"}})
        self.runtime = OrgFsRuntime(tmp_path / "orgfs", node_id="node-a", author=f"user:{OWNER}")
        self.fs = self.runtime.facade
        self.space_id = self.fs.create_space("personal-owner").space_id
        self.store = storage.FixedSpaceResolver(self.fs, self.space_id).store_for(SUB)
        self.registry = AgentRegistry(self.state / "agents.sqlite3", owner=OWNER, machine="pk-node",
                                      hyprial_home=self.home)
        self.agent = self.registry.create("worker")
        self.signer = bound_signer(self.state)
        self.anchor = Anchor(self.signer)
        self.clock = [NOW]
        self.app = SimpleNamespace(
            hyprial_home=self.home, state_dir=self.state, owner=OWNER, agents=self.registry,
            _user_key_signer=self.signer,
            _provider_key_space_resolver=storage.FixedSpaceResolver(self.fs, self.space_id),
            _provider_key_owner_key_port=self.anchor,
            _provider_key_clock=lambda: self.clock[0],
        )

    def settings(self, value: Any) -> None:
        (self.home / "settings.json").write_text(json.dumps(value), encoding="utf-8")

    def service(self) -> Any:
        return context.service_for(self.app)

    def ref(self, name: str = "worker") -> Any:
        return context.resolve_agent(self.app, name, None)

    def read_json(self, path: str) -> Any:
        found = self.store.read(path)
        return None if found is None else json.loads(found[0])

    def overwrite(self, path: str, value: Any) -> None:
        _, version = self.store.read(path)
        self.store.write(path, json.dumps(value), expect_version=version, create_only=False)

    def login(self, provider: str = "anthropic", secret: str = SECRET, **kwargs: Any) -> dict:
        return self.service().login(provider=provider, kind="api-key", secret=secret, **kwargs)["key"]

    def sentinel_hits(self, *values: str) -> list[str]:
        """Every file under tmp_path whose bytes contain a sentinel, raw or base64-encoded."""
        needles = [value.encode() for value in values]
        needles += [base64.b64encode(value.encode()) for value in values]
        hits = []
        for path in self.tmp.rglob("*"):
            if path.is_file() and not path.is_symlink():
                data = path.read_bytes()
                if any(needle in data for needle in needles):
                    hits.append(str(path.relative_to(self.tmp)))
        return hits

    def close(self) -> None:
        self.registry.close()
        self.runtime.close()


