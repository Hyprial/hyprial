"""Carrier reconciliation; the daemon alone owns message settlement.

Partial batches replay their frozen cursor through the daemon. Only the daemon
can subtract terminal members and render new inline/spill text. The original
carrier row remains the turn-correlation identity until settlement.
The settle-hint endpoint omits system notices. A successful non-consuming list
must also exclude every member before hint-based removal; its notice rows are
unfiltered. A valid empty cursor replay is direct daemon settlement evidence.
A quiet-turn deadline releases local observation, never interrupts a native
turn, and never acknowledges an inbox message. Restart grants a fresh grace.
The deadline is re-derived on every reconcile while the snapshot remains
TURN_STARTED: a fact dropped under relay pressure is regenerated by the next
reconcile, and the runtime's expected_stage/attempt fencing makes a late
duplicate a no-op.
"""

from __future__ import annotations

import json
import time
from collections.abc import Mapping
from dataclasses import replace

from hyprial.daemon.impl.api import HarnessDelivery

from .interactive_carrier_runtime import (
    FETCHED,
    TURN_STARTED,
    CarrierDeliverySnapshot,
    CarrierFetchedSettled,
    CarrierStatusUnknown,
)

TURN_RECONCILE_IDLE_SECONDS = 900.0


class CarrierRecoveryMixin:
    def _enqueue_carrier_delivery(self, delivery: HarnessDelivery) -> bool:
        with self._carrier_io_lock:
            self._carrier_queue_context[delivery.delivery_id] = {
                "enqueuedAtMs": time.time_ns() // 1_000_000,
            }
        if self._pump.enqueue(delivery):
            return True
        with self._carrier_io_lock:
            self._carrier_queue_context.pop(delivery.delivery_id, None)
        return False

    def _prepare_dequeued_delivery(
        self, delivery: HarnessDelivery
    ) -> HarnessDelivery | None:
        dequeued_at = time.time_ns() // 1_000_000
        prepared = self._prepare_carrier_delivery(delivery, source="native-query")
        with self._carrier_io_lock:
            context = self._carrier_queue_context.pop(delivery.delivery_id, {})
            if prepared is None:
                self._carrier_skipped_deliveries.add(delivery.delivery_id)
        if prepared is None or "remainingMessageIds" in context:
            self._log(
                "info",
                "worker.carrier.dequeue.skipped"
                if prepared is None
                else "worker.carrier.dequeue.rerendered",
                messageId=delivery.delivery_id,
                batchMessageIds=list(delivery.message_ids or (delivery.delivery_id,)),
                enqueuedAtMs=context.get("enqueuedAtMs"),
                dequeuedAtMs=dequeued_at,
                settledAtMs=context.get("settledAtMs"),
                ackSource=context.get("ackSource"),
                remainingMessageIds=context.get("remainingMessageIds", []),
                reason=context.get("reason", "carrier-not-fetched"),
            )
        return prepared

    def _record_queue_settlement(
        self, state: CarrierDeliverySnapshot, *, method: str, remaining: tuple[str, ...]
    ) -> None:
        observed_at = time.time_ns() // 1_000_000
        with self._carrier_io_lock:
            context = self._carrier_queue_context.get(state.delivery.delivery_id)
            if context is not None:
                context.update(
                    settledAtMs=observed_at,
                    ackSource={"method": method, "observedAtMs": observed_at},
                    remainingMessageIds=list(remaining),
                    reason="partially-settled" if remaining else "all-members-settled",
                )

    def _prepare_carrier_delivery(
        self, delivery: HarnessDelivery, *, source: str | None = None
    ) -> HarnessDelivery | None:
        state = self._carrier_runtime.snapshot(delivery.delivery_id)
        if state is None or state.stage != FETCHED:
            return None
        if self._fetched_is_settled(state, source=source):
            return None
        if delivery.batch_cursor is None:
            return delivery
        try:
            response = self.daemon_request(
                "message.pending.batch", self._signed({"cursor": delivery.batch_cursor})
            )
            if not isinstance(response, Mapping) or response.get("ok") is not True:
                raise ValueError("inbox cursor replay unavailable")
            rows, block = response.get("items"), response.get("delivery")
            cursor = response.get("cursor")
            if (
                response.get("format") != "inbox-batch-v1"
                or not isinstance(rows, list)
                or not isinstance(block, Mapping)
                or type(response.get("itemCount")) is not int
                or response["itemCount"] != len(rows)
                or not isinstance(cursor, str)
                or not isinstance(block.get("text"), str)
                or any(
                    not isinstance(row, Mapping)
                    or not isinstance(row.get("messageId"), str)
                    for row in rows
                )
            ):
                raise ValueError("inbox cursor replay malformed")
            members = tuple(row["messageId"] for row in rows)
            original = set(state.delivery.message_ids or (state.delivery.delivery_id,))
            if not set(members) <= original or len(set(members)) != len(members):
                raise ValueError("inbox cursor replay changed batch membership")
            if not members:
                if block["text"]:
                    raise ValueError("empty inbox cursor replay has injection text")
                self._discard_settled_fetched(
                    state, source=source, method="message.pending.batch"
                )
                return None
            if not cursor or not block["text"]:
                raise ValueError("inbox cursor replay has no cursor or injection text")
            if set(members) != original:
                self._record_queue_settlement(
                    state, method="message.pending.batch", remaining=members
                )
                self._log(
                    "info",
                    "worker.carrier.fetched_filtered",
                    state=state,
                    source=source or ("recovery" if state.recovered else "drain"),
                    removedMemberCount=len(original) - len(members),
                    remainingMemberCount=len(members),
                    generation=state.generation,
                    attempt=state.attempt,
                )
            return replace(delivery, message=block["text"], batch_cursor=cursor)
        except Exception as error:  # noqa: BLE001
            self._log(
                "warn",
                "worker.carrier.error",
                state=state,
                stage="fetched-replay",
                error=str(error) or type(error).__name__,
            )
            return delivery

    def _fetched_is_settled(
        self, state: CarrierDeliverySnapshot, *, source: str | None = None
    ) -> bool:
        """Only explicit, successful per-member inbox answers permit removal."""
        members = state.delivery.message_ids or (state.delivery.delivery_id,)
        for message_id in members:
            try:
                response = self.daemon_request(
                    "message.settle_hint", self._signed({"messageId": message_id})
                )
                if (
                    not isinstance(response, Mapping)
                    or response.get("ok") is not True
                    or not isinstance(response.get("pending"), bool)
                ):
                    raise ValueError("inbox settlement answer unavailable")
            except Exception as error:  # noqa: BLE001
                self._log(
                    "warn",
                    "worker.carrier.error",
                    state=state,
                    stage="fetched-settlement",
                    error=str(error) or type(error).__name__,
                )
                return False
            if response["pending"]:
                return False
        try:
            listed = self.daemon_request("message.pending.list", self._signed())
            rows = listed.get("messages") if isinstance(listed, Mapping) else None
            if (
                not isinstance(listed, Mapping)
                or listed.get("ok") is not True
                or not isinstance(rows, list)
                or any(
                    not isinstance(row, Mapping)
                    or not isinstance(row.get("messageId"), str)
                    for row in rows
                )
            ):
                raise ValueError("inbox notice settlement answer unavailable")
            if any(row["messageId"] in members for row in rows):
                return False
        except Exception as error:  # noqa: BLE001
            self._log(
                "warn",
                "worker.carrier.error",
                state=state,
                stage="fetched-settlement",
                error=str(error) or type(error).__name__,
            )
            return False
        self._discard_settled_fetched(state, source=source)
        return True

    def _discard_settled_fetched(
        self,
        state: CarrierDeliverySnapshot,
        *,
        source: str | None = None,
        method: str = "message.settle_hint+message.pending.list",
    ) -> None:
        self._record_queue_settlement(state, method=method, remaining=())
        self._log(
            "info",
            "worker.carrier.fetched_skipped",
            state=state,
            stage="fetched-settlement",
            recoveredState="ALL_MEMBERS_SETTLED",
            source=source or ("recovery" if state.recovered else "drain"),
            generation=state.generation,
            attempt=state.attempt,
        )
        self._submit_carrier_fact(
            CarrierFetchedSettled(
                generation=state.generation,
                delivery_id=state.delivery.delivery_id,
                attempt=state.attempt,
            )
        )

    def _sweep_settled_fetched(self) -> None:
        for state in self._carrier_runtime.snapshots():
            if state.stage == FETCHED:
                self._fetched_is_settled(state, source="sweep")

    def _turn_reconcile_deadline(
        self, state: CarrierDeliverySnapshot, turn: Mapping[str, object] | None = None
    ) -> None:
        """Level inProgress and failed reads are not evidence of progress."""
        now = self._heartbeat_clock()
        progress = getattr(self, "_carrier_turn_progress", None)
        if progress is None:
            progress = self._carrier_turn_progress = {}
        key = (state.generation, state.delivery.delivery_id, state.attempt)
        signature = (
            json.dumps(
                {"status": turn.get("status"), "items": turn.get("items")},
                sort_keys=True,
                default=str,
            )
            if turn is not None
            else None
        )
        activity_reader = getattr(self.server, "turn_activity_sequence", None)
        activity = activity_reader(state.turn_id) if callable(activity_reader) else 0
        previous, previous_activity, last_progress = progress.get(
            key, (signature, activity, now)
        )
        changed = (
            signature is not None and signature != previous
        ) or activity > previous_activity
        if key not in progress or changed:
            self._log(
                "info",
                "worker.carrier.turn_progress",
                state=state,
                observation="progress" if changed else "initial",
                deadlineSeconds=TURN_RECONCILE_IDLE_SECONDS,
            )
        if changed:
            previous = signature if signature is not None else previous
            last_progress = now
        progress[key] = (previous, activity, last_progress)
        if now - last_progress < TURN_RECONCILE_IDLE_SECONDS:
            return
        message_id = state.delivery.delivery_id
        self._log(
            "warn",
            "worker.carrier.turn_status_unknown",
            state=state,
            stage="turn-reconcile-deadline",
            error="native turn status unknown",
            idleSeconds=now - last_progress,
            deadlineSeconds=TURN_RECONCILE_IDLE_SECONDS,
        )
        self._submit_carrier_fact(
            CarrierStatusUnknown(
                generation=state.generation,
                delivery_id=message_id,
                attempts=state.settlement_attempts,
                expected_stage=TURN_STARTED,
                attempt=state.attempt,
            )
        )
        with self._carrier_io_lock:
            client = self._carrier_clients.pop(message_id, None)
        if client is not None:
            client.supply_status_unknown(state.turn_id)
