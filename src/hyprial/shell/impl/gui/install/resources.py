"""Wheel-internal GUI assets and their provenance manifest.

The wheel carries a *built* GUI under ``hyprial/_gui`` plus ``release.json``.
The manifest is generated by the build hook from the exact Git tree that built
the wheel; the installed CLI verifies it before serving.  It is deliberately
not a release-authority or external checksum feed: it answers only "which
source commit and GUI build is in this wheel, and are those bytes intact?".
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from importlib.resources import files
import ntpath
from pathlib import Path, PurePosixPath, PureWindowsPath
import posixpath
import re
from typing import Any, Mapping
from urllib.parse import urlsplit, urlunsplit

SCHEMA_VERSION = 1
MANIFEST_NAME = "release.json"
ASSET_DIR_NAME = "_gui"
_COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")
_HTTP_SCHEMES = frozenset({"http", "https", "git+http", "git+https"})


class GuiAssetError(RuntimeError):
    """A wheel resource or manifest is absent, malformed, or unverifiable."""

    def __init__(self, code: str, message: str, data: dict[str, Any] | None = None):
        super().__init__(message)
        self.code = code
        self.data = data or {}


@dataclass(frozen=True)
class GuiAssets:
    """A verified asset directory and the provenance copied from its wheel."""

    root: Path
    manifest: Mapping[str, Any]

    @property
    def package_version(self) -> str:
        return str(self.manifest.get("packageVersion", ""))

    @property
    def source_commit(self) -> str:
        return str(self.manifest.get("sourceCommit", ""))

    @property
    def source_remote(self) -> str:
        return str(self.manifest.get("sourceRemote", ""))

    @property
    def gui_version(self) -> str:
        return str(self.manifest.get("guiVersion", ""))


def installed_asset_root() -> Path:
    """Return the wheel's ``hyprial/_gui`` directory."""
    return Path(str(files("hyprial"))) / ASSET_DIR_NAME


def load_assets(root: Path, *, verify: bool = True) -> GuiAssets:
    """Load and, by default, verify a complete wheel asset directory."""
    root = root.expanduser().resolve()
    manifest = read_manifest(root / MANIFEST_NAME)
    if verify:
        verify_manifest_files(root, manifest)
    return GuiAssets(root=root, manifest=manifest)


def read_manifest(path: Path) -> dict[str, Any]:
    """Read and structurally validate ``release.json`` without trusting it."""
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise GuiAssetError(
            "GUI_ASSETS_MISSING",
            f"the installed GUI manifest is missing: {path}; reinstall the "
            "hyprial wheel or pass an explicit built GUI directory",
            {"manifest": str(path)},
        ) from error
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            f"cannot read the installed GUI manifest {path}: {error}",
            {"manifest": str(path)},
        ) from error
    if not isinstance(payload, dict):
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            f"the installed GUI manifest {path} must contain a JSON object",
            {"manifest": str(path)},
        )
    _require_int(payload, "schemaVersion", path)
    if payload["schemaVersion"] != SCHEMA_VERSION:
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            f"unsupported GUI manifest schemaVersion {payload['schemaVersion']}; "
            f"expected {SCHEMA_VERSION}",
            {"manifest": str(path), "schemaVersion": payload["schemaVersion"]},
        )
    for key in ("packageVersion", "sourceRemote", "guiVersion"):
        value = payload.get(key)
        if not isinstance(value, str) or not value.strip():
            raise GuiAssetError(
                "GUI_MANIFEST_INVALID",
                f"GUI manifest field {key} must be a non-empty string",
                {"manifest": str(path), "field": key},
            )
    validate_source_remote(str(payload["sourceRemote"]), manifest=path)
    source_commit = payload.get("sourceCommit")
    if not isinstance(source_commit, str) or not _COMMIT_RE.fullmatch(source_commit):
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            "GUI manifest sourceCommit must be a full 40-character lowercase "
            "Git object id; the installed version cannot be traced",
            {"manifest": str(path), "sourceCommit": source_commit},
        )
    entries = payload.get("files")
    if not isinstance(entries, list) or not entries:
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            "GUI manifest files must be a non-empty list",
            {"manifest": str(path)},
        )
    seen: set[str] = set()
    for entry in entries:
        if not isinstance(entry, dict):
            raise GuiAssetError(
                "GUI_MANIFEST_INVALID",
                "GUI manifest file entries must be objects",
                {"manifest": str(path)},
            )
        relative = entry.get("path")
        if not isinstance(relative, str) or not _safe_relative(relative):
            raise GuiAssetError(
                "GUI_MANIFEST_INVALID",
                f"GUI manifest contains an unsafe file path: {relative!r}",
                {"manifest": str(path), "path": relative},
            )
        if relative in seen:
            raise GuiAssetError(
                "GUI_MANIFEST_INVALID",
                f"GUI manifest contains a duplicate file path: {relative}",
                {"manifest": str(path), "path": relative},
            )
        seen.add(relative)
        digest = entry.get("sha256")
        if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise GuiAssetError(
                "GUI_MANIFEST_INVALID",
                f"GUI manifest has an invalid sha256 for {relative}",
                {"manifest": str(path), "path": relative},
            )
        size = entry.get("size")
        if not isinstance(size, int) or isinstance(size, bool) or size < 0:
            raise GuiAssetError(
                "GUI_MANIFEST_INVALID",
                f"GUI manifest has an invalid size for {relative}",
                {"manifest": str(path), "path": relative},
            )
    if "index.html" not in seen:
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            "GUI manifest does not list the required index.html entry",
            {"manifest": str(path)},
        )
    return payload


def verify_manifest_files(root: Path, manifest: Mapping[str, Any]) -> None:
    """Reject missing files, size changes, or hash changes before serving."""
    for entry in manifest["files"]:
        relative = str(entry["path"])
        path = root / relative
        try:
            data = path.read_bytes()
        except OSError as error:
            raise GuiAssetError(
                "GUI_ASSETS_MISSING",
                f"installed GUI file is missing or unreadable: {path}: {error}",
                {"path": str(path), "manifest": str(root / MANIFEST_NAME)},
            ) from error
        if len(data) != entry["size"]:
            raise GuiAssetError(
                "GUI_ASSETS_INVALID",
                f"installed GUI file {relative} has size {len(data)}, "
                f"expected {entry['size']}",
                {"path": str(path)},
            )
        digest = hashlib.sha256(data).hexdigest()
        if digest != entry["sha256"]:
            raise GuiAssetError(
                "GUI_ASSETS_INVALID",
                f"installed GUI file {relative} failed its sha256 check",
                {"path": str(path), "expected": entry["sha256"], "actual": digest},
            )


def resolve_explicit_assets(home: Path) -> Path:
    """Select a built GUI directory without reading Git, Node, or npm.

    A source checkout may expose its built ``gui/dist`` child; a wheel or an
    already extracted UI may expose ``index.html`` directly.  A package.json
    alone is not enough for the installed normal path.
    """
    home = home.expanduser().resolve()
    if not home.is_dir():
        raise GuiAssetError(
            "GUI_HOME_INVALID",
            f"GUI asset directory does not exist: {home}",
            {"gui_home": str(home)},
        )
    for candidate in (home / "dist", home):
        if (candidate / "index.html").is_file():
            return candidate.resolve()
    raise GuiAssetError(
        "GUI_HOME_INVALID",
        f"{home} has no built GUI (expected dist/index.html or index.html); "
        "build the GUI first or omit HYPRIAL_GUI_HOME to use the installed wheel",
        {"gui_home": str(home)},
    )


def build_manifest(
    asset_root: Path,
    *,
    package_version: str,
    source_commit: str,
    source_remote: str,
    gui_version: str,
) -> dict[str, Any]:
    """Create the manifest the build hook writes into the wheel."""
    if not _COMMIT_RE.fullmatch(source_commit):
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            f"sourceCommit must be a full 40-character Git object id: {source_commit!r}",
        )
    for field, value in (
        ("packageVersion", package_version),
        ("sourceRemote", source_remote),
        ("guiVersion", gui_version),
    ):
        if not value.strip():
            raise GuiAssetError(
                "GUI_MANIFEST_INVALID", f"{field} must not be empty"
            )
    validate_source_remote(source_remote)
    entries: list[dict[str, Any]] = []
    root = asset_root.expanduser().resolve()
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(root).as_posix()
        if relative == MANIFEST_NAME:
            continue
        data = path.read_bytes()
        entries.append(
            {
                "path": relative,
                "size": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
            }
        )
    if not entries or not (root / "index.html").is_file():
        raise GuiAssetError(
            "GUI_ASSETS_MISSING",
            f"GUI build produced no index.html under {root}",
            {"root": str(root)},
        )
    return {
        "schemaVersion": SCHEMA_VERSION,
        "packageVersion": package_version,
        "sourceCommit": source_commit,
        "sourceRemote": source_remote,
        "guiVersion": gui_version,
        "files": entries,
    }


def write_manifest(asset_root: Path, manifest: Mapping[str, Any]) -> Path:
    path = asset_root / MANIFEST_NAME
    path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return path


def remote_has_credentials(remote: str) -> bool:
    """Whether a remote embeds an identity secret or opaque query data.

    A normal SSH identity such as ``ssh://git@host/repo`` is not a credential
    and is allowed.  HTTP(S) userinfo, explicit passwords, scp-like
    ``user:password@host:path`` forms, and query/fragment tokens are rejected or
    redacted before they can be written to a wheel, logged, or printed.
    """
    parsed = urlsplit(remote)
    if parsed.password is not None:
        return True
    if parsed.scheme in _HTTP_SCHEMES and parsed.username is not None:
        return True
    if parsed.query or parsed.fragment:
        return True
    if "://" not in remote and "@" in remote:
        userinfo, _, _host = remote.partition("@")
        if ":" in userinfo:
            return True
    return False


def redact_remote(remote: str) -> str:
    """Return a display-only remote with credentials and query data removed.

    The unredacted value is still used for the actual fetch; this helper exists
    only for startup JSON, human prompts, and error messages.
    """
    if not remote:
        return ""
    parsed = urlsplit(remote)
    scp_like = (
        "://" not in remote
        and "@" in remote
        and ":" in remote.partition("@")[0]
    )
    if not remote_has_credentials(remote) and not scp_like:
        return remote
    if parsed.scheme and parsed.netloc:
        host = parsed.hostname or ""
        if ":" in host and not host.startswith("["):
            host = f"[{host}]"
        try:
            port = parsed.port
        except ValueError:
            port = None
        if port is not None:
            host = f"{host}:{port}"
        userinfo = ""
        if (
            parsed.username
            and parsed.password is None
            and parsed.scheme not in _HTTP_SCHEMES
        ):
            userinfo = f"{parsed.username}@"
        return urlunsplit(
            (parsed.scheme, f"{userinfo}{host}", parsed.path, "", "")
        )
    if scp_like:
        rest = remote.partition("@")[2]
        return rest.split("?", 1)[0].split("#", 1)[0]
    return remote.split("?", 1)[0].split("#", 1)[0]


def validate_source_remote(remote: str, *, manifest: Path | None = None) -> None:
    """Reject credentials in a manifest provenance remote.

    A normal SSH identity such as ``ssh://git@host/repo`` is not a credential
    and is allowed.  HTTP(S) userinfo, explicit passwords, scp-like
    ``user:password@host:path`` forms, and query/fragment data are rejected
    before they can be written to a wheel or printed by the development prompt.
    """
    if remote_has_credentials(remote):
        data = {"manifest": str(manifest)} if manifest is not None else {}
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            "GUI manifest sourceRemote contains credentials or query data; "
            "refusing to record or fetch them",
            data,
        )


def _safe_relative(value: str) -> bool:
    """Accept only paths that stay below the asset root on POSIX and Windows.

    The wheel is installed on both platforms, so a manifest produced on one
    host must not be interpreted as an escape by the other.  Check both path
    flavours, their normalized forms, drive/UNC roots, and traversal parts.
    """
    if not value or "\x00" in value:
        return False
    posix = PurePosixPath(value)
    windows = PureWindowsPath(value)
    if posix.is_absolute() or windows.is_absolute():
        return False
    if windows.drive or windows.root:
        return False
    if ".." in posix.parts or ".." in windows.parts:
        return False
    if any(part.rstrip(" .") in {"", ".", ".."} for part in windows.parts):
        # Windows normalizes trailing dots/spaces; do not let ".. " escape.
        return False
    if value.startswith(("/", "\\")):
        return False
    posix_normalized = posixpath.normpath(value)
    windows_normalized = ntpath.normpath(value)
    if posix_normalized in {"", ".", ".."} or posix_normalized.startswith("../"):
        return False
    if windows_normalized in {"", ".", ".."} or windows_normalized.startswith(
        "..\\"
    ):
        return False
    if ntpath.isabs(windows_normalized) or ntpath.splitdrive(windows_normalized)[0]:
        return False
    return True


def _require_int(payload: Mapping[str, Any], key: str, path: Path) -> None:
    value = payload.get(key)
    if not isinstance(value, int) or isinstance(value, bool):
        raise GuiAssetError(
            "GUI_MANIFEST_INVALID",
            f"GUI manifest field {key} must be an integer",
            {"manifest": str(path), "field": key},
        )
