function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

/**
 * Build the static bundle. `out` defaults to dist/core; an explicit directory
 * (for example a temporary one) is written instead, and the receipt records the
 * exact bytes so the same inputs always produce the same manifest.
 */
export async function buildCore({ out, coreRoot = defaultCoreRoot } = {}) {
  const target = out ? resolve(out) : join(distRoot, 'core');
  await assertSafeOut(target);
  const verification = await verifyCoreRuntime({ coreRoot });
  if (verification.problems.length) {
    throw Object.assign(new Error(`The app core runtime is not browser clean: ${verification.problems.join('; ')}`), { code: 'CORE_BUILD_INVALID' });
  }
  const manifest = JSON.parse(await readFile(join(guiRoot, 'package.json'), 'utf8'));
  const contents = new Map();
  for (const name of verification.files) contents.set(`runtime/${name}`, await readFile(join(coreRoot, name)));
  contents.set('index.html', Buffer.from(renderIndexHtml(), 'utf8'));
  contents.set('entry.mjs', Buffer.from(renderEntry(), 'utf8'));
  contents.set('styles.css', Buffer.from(renderStyles(), 'utf8'));

  const files = {};
  for (const name of [...contents.keys()].sort()) {
    const bytes = contents.get(name);
    files[name] = { bytes: bytes.length, sha256: sha256(bytes) };
  }
  const receipt = {
    schema: RECEIPT_SCHEMA,
    product: manifest.name,
    version: manifest.version,
    transportKinds: [...CORE_TRANSPORT_KINDS],
    files,
  };
  await rm(target, { recursive: true, force: true });
  await mkdir(target, { recursive: true });
  for (const name of [...contents.keys()].sort()) {
    await mkdir(dirname(join(target, name)), { recursive: true });
    await writeFile(join(target, name), contents.get(name));
  }
  await writeFile(join(target, 'manifest.json'), `${JSON.stringify(receipt, null, 2)}\n`);
  return { status: 'built', out: target, files: [...Object.keys(files), 'manifest.json'].sort() };
}

async function main(argv) {
  let out;
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] !== '--out') {
      console.error(`Unknown argument: ${argv[index]} (supported: --out <dir>)`);
      return 1;
    }
    out = argv[index + 1];
    index += 1;
    if (!out) {
      console.error('--out requires a directory');
      return 1;
    }
  }
  try {
    console.log(JSON.stringify(await buildCore({ out })));
    return 0;
  } catch (error) {
    console.error(`App core build failed: ${error.message}`);
    return 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
