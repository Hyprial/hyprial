// Assemble the distributable static App Core bundle into dist/core/.
//
// There is no bundler: the browser bundle is the checked-in core ESM sources
// copied byte for byte next to a generated page, an external entry module, an
// external stylesheet and a hash receipt, so packaging can verify exactly what
// it ships. The page loads no inline script and no inline style (a strict
// WebView/desktop CSP must be able to run it), and before copying, the whole
// import closure of the public face `core/index.mjs` is resolved and rejected
// if it reaches a Node builtin, an external package, another GUI module or a
// network/storage global: Core stays a pure browser runtime.
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE_TRANSPORT_KINDS } from '../core/index.mjs';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const guiRoot = resolve(scriptDirectory, '..');
const defaultCoreRoot = join(guiRoot, 'core');
const distRoot = join(guiRoot, 'dist');
const ENTRY = 'index.mjs';
const RECEIPT_SCHEMA = 'hyprial.app-core-build/v1';

// Core is a browser runtime: Node is allowed in this build script and in tests,
// never in the module the page loads.
const FORBIDDEN_RUNTIME_GLOBALS = Object.freeze([
  /\bfetch\s*\(/, /\bXMLHttpRequest\b/, /\bWebSocket\b/, /\bEventSource\b/, /\bsendBeacon\b/,
  /\blocalStorage\b/, /\bsessionStorage\b/, /\bindexedDB\b/, /document\s*\.\s*cookie/,
]);
const SPECIFIER_PATTERN = /\b(?:import|export)\s+(?:[\s\S]*?\sfrom\s*)?['"]([^'"]+)['"]/g;
const DYNAMIC_SPECIFIER_PATTERN = /\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g;

function specifiers(source) {
  return [...source.matchAll(SPECIFIER_PATTERN), ...source.matchAll(DYNAMIC_SPECIFIER_PATTERN)].map(match => match[1]);
}

function unsafe(message) {
  throw Object.assign(new Error(message), { code: 'CORE_BUILD_OUT_UNSAFE' });
}

/**
 * The output directory is removed before it is written, so it must never be a
 * product source root, an ancestor of the GUI project, or an unrelated
 * directory that happens to have been named on the command line.
 */
async function assertSafeOut(target) {
  if (target === guiRoot || guiRoot.startsWith(`${target}${sep}`)) {
    unsafe(`Refusing to build into ${target}: it contains the GUI sources`);
  }
  if (target.startsWith(`${guiRoot}${sep}`) && target !== distRoot && !target.startsWith(`${distRoot}${sep}`)) {
    unsafe(`Refusing to build into ${target}: inside the GUI project but outside dist/`);
  }
  let entries;
  try {
    entries = await readdir(target);
  } catch {
    return;
  }
  if (!entries.length) return;
  let receipt;
  try {
    receipt = JSON.parse(await readFile(join(target, 'manifest.json'), 'utf8'));
  } catch {
    receipt = null;
  }
  if (receipt?.schema !== RECEIPT_SCHEMA) {
    unsafe(`Refusing to overwrite ${target}: it is not a previous app core build`);
  }
}

/** Resolve the runtime import closure of core/index.mjs and report any leak. */
export async function verifyCoreRuntime({ coreRoot = defaultCoreRoot } = {}) {
  const root = resolve(coreRoot);
  const files = [];
  const problems = [];
  const queue = [ENTRY];
  const seen = new Set();
  while (queue.length) {
    const name = queue.shift();
    if (seen.has(name)) continue;
    seen.add(name);
    let source;
    try {
      source = await readFile(join(root, name), 'utf8');
    } catch {
      problems.push(`${name}: core runtime file is missing`);
      continue;
    }
    files.push(name);
    for (const pattern of FORBIDDEN_RUNTIME_GLOBALS) {
      if (pattern.test(source)) problems.push(`${name}: core runtime must not use network or storage globals (${pattern})`);
    }
    for (const specifier of specifiers(source)) {
      if (!specifier.startsWith('./')) {
        problems.push(`${name}: core runtime must not import '${specifier}' (Node builtin or external dependency)`);
        continue;
      }
      const target = relative(root, resolve(dirname(join(root, name)), specifier)).split(sep).join('/');
      if (target.startsWith('..')) problems.push(`${name}: '${specifier}' escapes the app core module`);
      else queue.push(target);
    }
  }
  return { root, files: files.sort(), problems };
}

