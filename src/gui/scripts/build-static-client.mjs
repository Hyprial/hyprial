import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
await import('../packages/gui-layout/build.mjs');
let source = await readFile(resolve(root, 'imskin-plugin.js'), 'utf8');
const styleSource = (await readFile(resolve(root, 'shared/gui-style.mjs'), 'utf8')).replace(/^export /gm, '');
source = source.replace(/    \/\/ BEGIN GUI STYLE CONTRACT[\s\S]*?    \/\/ END GUI STYLE CONTRACT/, () => '    // BEGIN GUI STYLE CONTRACT\n' + styleSource + '\n    // END GUI STYLE CONTRACT');
for (const [name, file] of [['WORKFLOW WORKBENCH', 'workflow-workbench'], ['GUI WORKSPACE', 'gui-workspace'], ['GUI MODULE RUNTIME', 'gui-module-runtime'], ['GUI BUSINESS VIEWS', 'gui-business'], ['GUI KANBAN VIEWS', 'gui-kanban'], ['GUI PROFILE', 'gui-profile'], ['GUI EDITOR', 'gui-editor'], ['GUI AUTHORING', 'gui-authoring'], ['GUI STUDIO', 'gui-studio']]) {
  const included = await readFile(resolve(root, `client/${file}.inc.js`), 'utf8');
  const region = new RegExp('    // BEGIN ' + name + '[\\s\\S]*?    // END ' + name);
  if (!region.test(source)) throw new Error('imskin-plugin.js has no ' + name + ' include region');
  source = source.replace(region, () => '    // BEGIN ' + name + '\n' + included + '    // END ' + name);
}
const guiCss = (await Promise.all(['gui-studio', 'gui-editor', 'gui-business', 'gui-theme'].map(file => readFile(resolve(root, 'client/' + file + '.css'), 'utf8')))).join('\n');
source = source.replace(/    \/\/ BEGIN GUI STYLES[\s\S]*?    \/\/ END GUI STYLES/, () => '    // BEGIN GUI STYLES\n    styles.insert(' + JSON.stringify(guiCss) + ');\n    // END GUI STYLES');
await writeFile(resolve(root, 'imskin-plugin.js'), source);
const match = /^return \{/m.exec(source);
if (!match) throw new Error('imskin-plugin.js has no line-leading return block');
const pluginBody = source.slice(match.index).replace(/^return \{/m, 'const staticPlugin = {');
const moduleId = '@hyprial/dsh-h2b-talk';
const output = `// Generated by scripts/build-static-client.mjs. Do not edit directly.\n` +
`window.__ModuleLoader__.load({\n` +
`  id: ${JSON.stringify(moduleId)},\n` +
`  factory: (require) => {\n` +
`    const module = { exports: {} };\n` +
`    const exports = module.exports;\n` +
`    const React = require('react');\n` +
`    const styles = { insert(css) {\n` +
`      const tag = document.createElement('style');\n` +
`      tag.dataset.plugin = ${JSON.stringify(moduleId)};\n` +
`      tag.textContent = css;\n` +
`      document.head.append(tag);\n` +
`      return () => tag.remove();\n` +
`    } };\n` +
`    const host = { async call(method, args) {\n` +
`      const response = await fetch('/plugins/h2b-talk/rpc', {\n` +
`        method: 'POST', headers: { 'content-type': 'application/json' },\n` +
`        body: JSON.stringify({ method, args })\n` +
`      });\n` +
`      const result = await response.json();\n` +
`      if (!response.ok || !result || result.ok !== true) {\n` +
`        const error = new Error(result?.error?.message || 'H2B host request failed');\n` +
`        error.code = result?.error?.code || 'HOST_ERROR';\n` +
`        if (result?.error?.details !== undefined) error.details = result.error.details;\n` +
`        throw error;\n` +
`      }\n` +
`      return result.value;\n` +
`    } };\n` +
pluginBody.split('\n').map((line) => line ? `    ${line}` : '').join('\n') + `\n` +
`    exports.apply = staticPlugin.apply;\n` +
`    exports.inject = staticPlugin.inject;\n` +
`    return module.exports;\n` +
`  }\n` +
`});\n`;

const target = resolve(root, 'static/client.js');
await mkdir(dirname(target), { recursive: true });
await writeFile(target, output);
