# Decision record (file header; no inline comments by repository rule):
# - The coverage table is derived statically (AST scan of `@case("ID")`
#   decorators under cases/), so it needs no engine and cannot be faked by a
#   run that skipped tests. The meta case fails if COVERAGE.md is stale or if
#   any spec section 14 ID has no test.
# - Regenerate with: cd conformance/actor_engine && python -m support.coverage
"""Generate and check COVERAGE.md (case ID <-> test mapping)."""

from __future__ import annotations

import ast
import sys
from pathlib import Path

from support.catalog import CASES

SUITE = Path(__file__).resolve().parents[1]
TABLE = SUITE / "COVERAGE.md"


def scan() -> dict[str, list[str]]:
    found: dict[str, list[str]] = {case_id: [] for case_id, *_ in CASES}
    for path in sorted((SUITE / "cases").rglob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        rel = path.relative_to(SUITE).as_posix()
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for deco in node.decorator_list:
                if (isinstance(deco, ast.Call) and deco.args
                        and isinstance(deco.args[0], ast.Constant)
                        and _decorator_name(deco.func) == "case"):
                    found.setdefault(str(deco.args[0].value), []).append(f"{rel}::{node.name}")
    return found


def _decorator_name(func: ast.expr) -> str:
    if isinstance(func, ast.Name):
        return func.id
    if isinstance(func, ast.Attribute):
        return func.attr
    return ""


def render(found: dict[str, list[str]]) -> str:
    lines = [
        "# Conformance coverage: spec section 14 case ID <-> test",
        "",
        "Generated by `python -m support.coverage` (run inside `conformance/actor_engine`).",
        "Do not edit by hand; `cases/meta/test_catalog.py` fails when this file is stale.",
        "",
        f"Cases: {len(CASES)}; covered: {sum(1 for c, *_ in CASES if found.get(c))}.",
        "",
        "| case | group | title | clauses | tests |",
        "|---|---|---|---|---|",
    ]
    for case_id, group, title, clauses in CASES:
        tests = "<br>".join(f"`{t}`" for t in found.get(case_id, [])) or "**MISSING**"
        lines.append(f"| {case_id} | {group} | {title.replace('|', '/')} | {clauses} | {tests} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    TABLE.write_text(render(scan()), encoding="utf-8")
    sys.stdout.write(f"wrote {TABLE}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
