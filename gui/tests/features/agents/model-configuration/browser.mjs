/** Real shared App interactions over canonical Contract Mock; no vendor/backend claim. */
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium } from 'playwright-core';
import { startGuiServer } from '../../../../scripts/serve.mjs';
import { browserExecutable } from '../../../support/browser.mjs';
const root = resolve(import.meta.dirname, '../../../..');
process.env.HYPRIAL_GUI_HOME = root;
const server = await startGuiServer({ mode: 'development', host: '127.0.0.1', port: 0, strictPort: true });
const browser = await chromium.launch({ executablePath: browserExecutable() });
const evidence = process.env.HYPRIAL_BROWSER_EVIDENCE_DIR || '/private/tmp/pr6-browser';
try {
  await mkdir(evidence, { recursive: true });
  for (const width of [1440, 390, 375, 760]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => {
      crypto.randomUUID = () => '00000000-0000-4000-8000-000000000001';
    });
    const entry = new URL('tests/features/agents/model-configuration/entry.html', server.url);
    await page.goto(entry.href);
    await page.getByRole('button', { name: 'Agent', exact: true }).click();
    await page.getByRole('button', { name: '创建 Agent', exact: true }).click();
    await page.getByLabel('名称', { exact: true }).fill('worker');
    await page.getByLabel('harness', { exact: true }).click();
    await page.getByRole('option', { name: 'pi', exact: true }).click();
    await page.getByLabel('连接', { exact: true }).click();
    await page.getByRole('option', { name: /example-custom/ }).click();
    await page.getByLabel('模型 ID', { exact: true }).fill('hy4-flash');
    assert.equal(await page.getByLabel('模型服务商', { exact: true }).count(), 0);
    await page.screenshot({ path: resolve(evidence, `create-${width}.png`) });
    await page.getByRole('button', { name: '创建 Agent', exact: true }).click();
    await page.getByRole('heading', { name: '模型配置', exact: true }).waitFor();
    await page.getByText('pi · 连接 / Key · hy4-flash · 后台运行', { exact: true }).waitFor();
    await page.getByRole('button', { name: '启动', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '启动 Agent' });
    await dialog.waitFor();
    assert.equal(await dialog.getByRole('combobox').count(), 0);
    await dialog.getByLabel('工作目录', { exact: true }).fill('/work/worker');
    await dialog.getByRole('checkbox').check();
    await page.screenshot({ path: resolve(evidence, `start-${width}.png`) });
    await dialog.getByRole('button', { name: '启动', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '配置模型', exact: true }).click();
    const edit = page.getByRole('dialog', { name: '配置模型', exact: true });
    await edit.waitFor();
    await edit.getByLabel('模型 ID', { exact: true }).fill('qwen3.7-flash');
    await page.keyboard.press('Escape');
    await edit.waitFor({ state: 'hidden' });
    await page.getByText('pi · 连接 / Key · hy4-flash · 后台运行', { exact: true }).waitFor();
    entry.searchParams.set('pending', '1');
    await page.goto(entry.href);
    await page.getByRole('button', { name: 'Agent', exact: true }).click();
    const card = page.getByTestId('contact-worker');
    await page.screenshot({ path: resolve(evidence, `pending-list-${width}.png`) });
    await card.click();
    await page.getByRole('button', { name: '取消未完成配置', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: '配置模型', exact: true }).isEnabled(), false);
    await page.getByRole('button', { name: '启动', exact: true }).click();
    assert.equal(await page.getByRole('dialog', { name: '启动 Agent' }).count(), 0);
    await page.getByRole('button', { name: '取消未完成配置', exact: true }).click();
    await page.getByText('配置操作已取消；保留原绑定。', { exact: true }).waitFor();
    await page.screenshot({ path: resolve(evidence, `cancel-${width}.png`) });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ width, passed: true, driver: 'canonical-contract-mock', pageErrors: errors }));
    await page.close();
    const legacy = await browser.newPage({ viewport: { width, height: 900 } });
    const legacyErrors = [];
    legacy.on('pageerror', error => legacyErrors.push(error.message));
    entry.searchParams.delete('pending');
    entry.searchParams.set('source', 'startup');
    await legacy.goto(entry.href);
    await legacy.getByRole('button', { name: 'Agent', exact: true }).click();
    await legacy.getByRole('button', { name: '创建 Agent', exact: true }).click();
    await legacy.getByLabel('名称', { exact: true }).fill(`preview-${width}`);
    await legacy.getByLabel('harness', { exact: true }).click();
    await legacy.getByRole('option', { name: 'pi', exact: true }).click();
    await legacy.getByLabel('模型', { exact: true }).waitFor();
    assert.equal(await legacy.getByLabel('模型 ID', { exact: true }).count(), 0);
    await legacy.screenshot({ path: resolve(evidence, `startup-create-${width}.png`) });
    await legacy.getByRole('button', { name: '创建 Agent', exact: true }).click();
    await legacy.getByRole('button', { name: '启动', exact: true }).waitFor();
    assert.equal(await legacy.getByRole('heading', { name: '模型配置', exact: true }).count(), 0);
    await legacy.getByRole('button', { name: '启动', exact: true }).click();
    const legacyStart = legacy.getByRole('dialog', { name: '启动 Agent' });
    await legacyStart.waitFor();
    await legacyStart.getByLabel('工作目录', { exact: true }).fill('/preview/work');
    await legacyStart.getByRole('checkbox').check();
    await legacyStart.getByRole('button', { name: '保存并启动', exact: true }).click();
    await legacyStart.waitFor({ state: 'hidden' });
    await legacy.getByRole('button', { name: '停止', exact: true }).click();
    await legacy.getByRole('button', { name: '启动', exact: true }).waitFor();
    await legacy.screenshot({ path: resolve(evidence, `startup-stopped-${width}.png`) });
    assert.deepEqual(legacyErrors, []);
    console.log(JSON.stringify({ width, passed: true, driver: 'legacy-startup-preview', pageErrors: legacyErrors }));
    await legacy.close();
  }
} finally {
  await browser.close();
  await server.close();
}
