// @vitest-environment node
/**
 * Contract Mock patterns answer like Python `re` (the daemon's validator).
 *
 * Decision record (1e-2 after review, 2026-11-15)
 * - Field probes: the inputs the first comparison did not contain. A trailing
 *   newline after `$`, the whitespace characters on which Python and
 *   ECMAScript disagree (U+001C-001F and U+0085 are whitespace only in Python,
 *   U+FEFF only in ECMAScript) and `.`/line terminators, applied through the
 *   real params schemas of the fields that carry the patterns.
 * - Differential: `pattern-parity.fixture.json` holds Python's verdict for
 *   every distinct pattern of the contract over an edge-character input set.
 *   It is generated by `scripts/verify/gen_pattern_parity.py`, and a pytest
 *   runs that script with `--check`. The set of patterns must equal the set
 *   the real table carries, so a new pattern forces a new fixture.
 * - Translation table rows and refusals of untranslatable constructs are
 *   tested on the translator directly.
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { compilePattern, projectContract, pythonPattern, schemaErrors, withDigest } from '../../contract-mock/index.ts';
import type { ContractTable } from '../../contract-mock/index.ts';
import { realEnvelope, realOpenapi } from './synthetic.ts';

const table: ContractTable = withDigest(projectContract(realOpenapi(), realEnvelope()));

interface Fixture {
  patterns: { pattern: string; inputs: string[]; verdicts: string }[];
}

const fixture: Fixture = JSON.parse(
  readFileSync(fileURLToPath(new URL('./pattern-parity.fixture.json', import.meta.url)), 'utf8'),
);

function collect(schema: unknown, out: Set<string>): Set<string> {
  if (Array.isArray(schema)) schema.forEach((item) => collect(item, out));
  else if (typeof schema === 'object' && schema !== null) {
    const record = schema as Record<string, unknown>;
    if (typeof record.pattern === 'string') out.add(record.pattern);
    Object.values(record).forEach((child) => collect(child, out));
  }
  return out;
}

function baseParams(method: string): Record<string, unknown> {
  const entry = table.methods[method];
  const usable = entry.examples.find(
    (example) => example.kind !== 'invalid-params' && schemaErrors(entry.paramsSchema, example.params).length === 0,
  );
  if (usable === undefined) throw new Error(`${method}: no schema-valid example`);
  return structuredClone(usable.params as Record<string, unknown>);
}

function fieldAccepts(method: string, field: string, value: unknown): boolean {
  const params = { ...baseParams(method), [field]: value };
  return !schemaErrors(table.methods[method].paramsSchema, params).some((path) => path[0] === field);
}

describe('fields that carry a pattern', () => {
  it('accepts a trailing newline after an end anchor like Python', () => {
    expect(fieldAccepts('auth.login.begin', 'operationKey', 'opkey-0123456789abcdef')).toBe(true);
    expect(fieldAccepts('auth.login.begin', 'operationKey', 'opkey-0123456789abcdef\n')).toBe(true);
    expect(fieldAccepts('auth.login.begin', 'operationKey', 'opkey-0123456789abcdef\n\n')).toBe(false);
    expect(fieldAccepts('auth.login.begin', 'operationKey', '\nopkey-0123456789abcdef')).toBe(false);
    expect(fieldAccepts('auth.login.begin', 'operationKey', 'opkey-0123456789abcdef\r')).toBe(false);
  });

  it.each(['\x1c', '\x1d', '\x1e', '\x1f', '\x85'])('treats %j as whitespace for \\S like Python', (char) => {
    expect(fieldAccepts('message.send', 'summary', char)).toBe(false);
    expect(fieldAccepts('message.send', 'summary', `${char}${char}`)).toBe(false);
    expect(fieldAccepts('message.send', 'summary', `${char}x`)).toBe(true);
  });

  it('does not treat U+FEFF as whitespace for \\S like Python', () => {
    expect(fieldAccepts('message.send', 'summary', '\ufeff')).toBe(true);
  });

  it('applies the same whitespace set inside a class', () => {
    const accepts = (value: string) => fieldAccepts('message.send', 'to', [value]);
    expect(accepts('agent:a:b:c')).toBe(true);
    expect(accepts('agent:a:b:c\n')).toBe(true);
    expect(accepts('agent:\x1c:b:c')).toBe(false);
    expect(accepts('agent:\x85:b:c')).toBe(false);
    expect(accepts('agent:\ufeff:b:c')).toBe(true);
    expect(accepts('agent:a:b:c\n\n')).toBe(false);
  });
});

describe('translation', () => {
  it.each([
    ['$ outside a class', 'a$', '(?=\\n?$)'],
    ['. outside a class', 'a.b', '[^\\n]'],
    ['\\s outside a class', '\\s', '\\u{1c}-\\u{20}'],
    ['\\S inside a class', '[^:\\S]', '\\u{21}-\\u{84}'],
  ])('rewrites %s', (_name, source, fragment) => {
    expect(pythonPattern(source)).toContain(fragment);
  });

  it('leaves a $ inside a class and an escaped $ alone', () => {
    expect(pythonPattern('[$.]')).toBe('[$.]');
    expect(pythonPattern('\\$\\.')).toBe('\\$\\.');
  });

  it.each(['\\d', '\\D', '\\w', '\\W', '\\b', '\\B', '\\p{L}', '(\\w)\\1', '(?<n>a)', '(?i)a', 'a{,3}', '[[a]', '\\u{1f600}', '[a', '\\q'])(
    'refuses the construct %s at load',
    (source) => {
      expect(() => pythonPattern(source, 'probe')).toThrow(/probe: unsupported pattern construct/);
    },
  );

  it('refuses an untranslatable pattern while a table loads', () => {
    const document = realOpenapi();
    const operation = document.paths['/daemon/request/auth.login.begin'].post;
    operation.requestBody.content['application/json'].schema.properties.operationKey.pattern = '^\\d+$';
    expect(() => projectContract(document, realEnvelope())).toThrow(/unsupported pattern construct \\d/);
  });
});

describe('differential against Python re', () => {
  it('covers every pattern the mock evaluates and every pattern of the contract', () => {
    const served = new Set<string>();
    for (const entry of Object.values(table.methods)) collect(entry.paramsSchema, served);
    const declared = new Set<string>();
    const document = realOpenapi();
    for (const item of Object.values<any>(document.paths)) collect(item.post.requestBody?.content?.['application/json']?.schema, declared);
    for (const entry of document['x-hyprial-methods'] ?? []) collect(entry.paramsSchema, declared);
    const recorded = fixture.patterns.map((entry) => entry.pattern).sort();
    expect(recorded).toEqual([...declared].sort());
    expect([...served].filter((pattern) => !recorded.includes(pattern))).toEqual([]);
  });

  it.each(fixture.patterns.map((entry) => [entry.pattern, entry] as const))('%s matches Python on every input', (_pattern, entry) => {
    expect(entry.verdicts.length).toBe(entry.inputs.length);
    const regex = compilePattern(entry.pattern);
    const differing = entry.inputs.filter((input, index) => regex.test(input) !== (entry.verdicts[index] === '1'));
    expect(differing.map((input) => JSON.stringify(input))).toEqual([]);
  });

  it('is sensitive to the dialect: raw ECMAScript semantics would differ', () => {
    let differences = 0;
    for (const entry of fixture.patterns) {
      const raw = new RegExp(entry.pattern, 'u');
      differences += entry.inputs.filter((input, index) => raw.test(input) !== (entry.verdicts[index] === '1')).length;
    }
    expect(differences).toBeGreaterThan(20);
  });
});
