"""Explicit symbol extraction: top-level definitions and class collaborators.

Rule kinds:

- ``symbol_extract``: moves whole top-level definitions (``def``/``class``/
  assignments named in ``symbols``) from ``source_path`` into ``target_path``.
  Free variables of the moved code must be covered by the explicit
  ``dependencies`` list (``import``, ``companion`` or ``wrapper_param``
  provisions) or the rule fails. Optional ``registration`` wraps the moved
  definitions into a generated ``register_x(app)``-style function whose call
  replaces the first moved statement, preserving registration order.
- ``class_member_extract``: moves named methods of one class into a new
  collaborator class. Every ``self.X`` access must be classified by the
  explicit dependency list as ``field``, ``host`` or ``class_attr`` (or be a
  moved method itself). Zero-arg ``super()`` inside moved methods is
  refused. The host keeps signature-preserving shims for methods still
  called from remaining host code (plus explicit ``shim_methods``), and
  receives the manifest's trusted ``wiring`` statement appended to a named
  method.

Code is located by name inside the hash-pinned source file; line numbers are
never used to find definitions.
"""

from __future__ import annotations

import hashlib

import libcst as cst

from .common import Diagnostic, ERROR, Rule, RuleOutcome, decode_source
from .parsing import ParsedPython, TransformContext, assign_target_names

KINDS = ("symbol_extract", "class_member_extract")

GENERATED_NOTE = "generated by scripts/refactor"


class _Refusal(Exception):
    def __init__(self, code: str, message: str, line: int | None = None) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.line = line


def _walk(node: cst.CSTNode):
    stack = [node]
    while stack:
        current = stack.pop()
        yield current
        stack.extend(reversed(list(current.children)))


def _module_level_binding(assignment) -> bool:
    return type(assignment.scope).__name__ == "GlobalScope"


def _free_variables(parsed: ParsedPython, roots: list[cst.CSTNode]) -> set[str]:
    """Names accessed inside `roots` that bind in the source file's global scope."""
    scopes = parsed.scopes()
    free: set[str] = set()
    for root in roots:
        for node in _walk(root):
            if not isinstance(node, cst.Name):
                continue
            scope = scopes.get(node)
            if scope is None:
                continue
            try:
                assignments = scope[node.value]
            except KeyError:
                continue
            for assignment in assignments:
                if _module_level_binding(assignment):
                    free.add(node.value)
                    break
    return free


def _parse_expr_names(text: str) -> set[str]:
    import ast

    try:
        tree = ast.parse(text, mode="eval")
    except SyntaxError:
        return set()
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            names.add(node.id)
    return names


def _annotation_string_names(parsed: ParsedPython, roots: list[cst.CSTNode]) -> set[str]:
    """Free names in quoted annotations (only strings in annotation positions)."""
    parents = parsed.build_parent_map()
    names: set[str] = set()
    annotation_owners = (cst.AnnAssign, cst.Param, cst.FunctionDef)
    for root in roots:
        for node in _walk(root):
            if not isinstance(node, cst.SimpleString):
                continue
            owner = parents.get(id(node))
            if not isinstance(owner, annotation_owners):
                continue
            if isinstance(owner, cst.AnnAssign) and owner.annotation is not node:
                continue
            if isinstance(owner, cst.Param) and owner.annotation is not node:
                continue
            if isinstance(owner, (cst.FunctionDef)) and owner.returns is not node:
                continue
            names |= _parse_expr_names(node.raw_value)
    return names


def _remove_self(params: cst.Parameters) -> cst.Parameters:
    new_params = list(params.params)
    if new_params and new_params[0].name.value == "self":
        new_params = new_params[1:]
    return params.with_changes(params=new_params)


def _render_annotation(node: cst.CSTNode) -> str:
    inner = node.annotation if isinstance(node, cst.Annotation) else node
    return cst.Module(body=[]).code_for_node(inner)


def _render_params(params: cst.Parameters) -> str:
    holder = cst.FunctionDef(
        name=cst.Name("_render"),
        params=params,
        body=cst.SimpleStatementSuite(body=[cst.Pass()]),
    )
    holder_module = cst.Module(body=[holder])
    first_line = holder_module.code.splitlines()[0]
    start = first_line.index("(") + 1
    end = first_line.rindex("):")
    return first_line[start:end]


def _render_shim(method_node: cst.FunctionDef, host_attribute: str) -> str:
    # the shim stays a method on the host: keep `self` in the signature,
    # forward every non-self argument to the collaborator, and preserve the
    # decorators and return annotation so call-site semantics do not change
    call_params = _remove_self(method_node.params)
    call_args: list[str] = []
    for p in call_params.params:
        call_args.append(p.name.value)
    if isinstance(call_params.star_arg, cst.Param):
        call_args.append("*" + call_params.star_arg.name.value)
    for p in call_params.kwonly_params:
        call_args.append(f"{p.name.value}={p.name.value}")
    if isinstance(call_params.star_kwarg, cst.Param):
        call_args.append("**" + call_params.star_kwarg.name.value)
    decorator_names = {
        _render_annotation(d.decorator) for d in method_node.decorators
    }
    if "property" in decorator_names:
        # a property shim forwards the attribute itself, not a call result
        call = f"self.{host_attribute}.{method_node.name.value}"
    else:
        call = (
            f"self.{host_attribute}.{method_node.name.value}({', '.join(call_args)})"
        )
    is_async = method_node.asynchronous is not None
    await_prefix = "await " if is_async else ""
    has_return = method_node.returns is not None or _needs_return(method_node)
    prefix = "async def" if is_async else "def"
    annotation = ""
    if method_node.returns is not None:
        annotation = f" -> {_render_annotation(method_node.returns)}"
    signature = (
        f"{prefix} {method_node.name.value}({_render_params(method_node.params)}){annotation}:"
    )
    body = f"return {await_prefix}{call}" if has_return else f"{await_prefix}{call}"
    decorators = "".join(
        f"@{_render_annotation(d.decorator)}\n" for d in method_node.decorators
    )
    return f"{decorators}{signature}\n    {body}"


def _needs_return(node: cst.CSTNode) -> bool:
    """A shim must return when the method returns a value OR is a generator
    (the delegated call produces the generator object that must propagate)."""
    for sub in _walk(node):
        if isinstance(sub, cst.Return) and sub.value is not None:
            return True
        if isinstance(sub, cst.Yield):
            return True
        if isinstance(sub, cst.Await) and False:
            pass
    return False


class _SourceAnalysis:
    def __init__(self, parsed: ParsedPython) -> None:
        self.top_level: dict[str, cst.CSTNode] = {}
        self.classes: dict[str, cst.ClassDef] = {}
        self.all_names: set[str] = set()
        for statement in parsed.module.body:
            if isinstance(statement, (cst.FunctionDef, cst.ClassDef)):
                self.top_level[statement.name.value] = statement
                if isinstance(statement, cst.ClassDef):
                    self.classes[statement.name.value] = statement
                continue
            if isinstance(statement, cst.SimpleStatementLine):
                for small in statement.body:
                    if isinstance(small, cst.Assign):
                        target_names = assign_target_names(small)
                        for target_name in target_names:
                            self.top_level[target_name] = small
                        if "__all__" in target_names and isinstance(
                            small.value, (cst.List, cst.Tuple)
                        ):
                            for element in small.value.elements:
                                if isinstance(element, cst.SimpleString):
                                    self.all_names.add(element.raw_value)
                    elif isinstance(small, cst.AnnAssign) and isinstance(small.target, cst.Name):
                        self.top_level[small.target.value] = small


def _indent(text: str, spaces: str = "    ") -> str:
    return "\n".join(spaces + line if line.strip() else line for line in text.splitlines())


def _dep_import_lines(dep_map: dict[str, dict], names: list[str]) -> list[str]:
    lines = []
    for name in names:
        dep = dep_map[name]
        if dep.get("provision") != "import":
            continue
        module = str(dep["module"])
        symbol = str(dep.get("symbol", name))
        if str(dep.get("asname", name)) != symbol:
            lines.append(f"from {module} import {symbol} as {dep.get('asname', name)}")
        else:
            lines.append(f"from {module} import {symbol}")
    return sorted(set(lines))



def _dependency_module_known(ws, module: str) -> bool:
    """A dependency module is known when it is a tracked project module or stdlib."""
    if ws.index.is_module(module):
        return True
    import sys

    root = module.split(".")[0]
    return root in getattr(sys, "stdlib_module_names", ())

def _check_dependencies(
    dep_map: dict[str, dict],
    free: set[str],
    extracted: set[str],
    registration: dict | None,
    wrapper_param: str | None,
    ws,
    outcome: RuleOutcome,
) -> None:
    uncovered = []
    for name in sorted(free):
        dep = dep_map.get(name)
        if dep is None:
            uncovered.append(name)
            continue
        provision = dep.get("provision")
        if provision == "import":
            module = dep.get("module")
            if not module or not _dependency_module_known(ws, str(module)):
                raise _Refusal(
                    "DEPENDENCY-MODULE-UNKNOWN",
                    f"dependency {name!r} imports from unknown module {module!r}",
                )
        elif provision == "wrapper_param":
            if registration is None:
                raise _Refusal(
                    "DEPENDENCY-PROVISION-INVALID",
                    f"dependency {name!r} uses wrapper_param but no registration is configured",
                )
            if wrapper_param is not None and name != wrapper_param:
                raise _Refusal(
                    "DEPENDENCY-PROVISION-INVALID",
                    f"wrapper_param dependency {name!r} does not match wrapper parameter "
                    f"{wrapper_param!r}",
                )
        elif provision == "companion":
            if str(dep.get("symbol", name)) not in extracted:
                raise _Refusal(
                    "DEPENDENCY-PROVISION-INVALID",
                    f"companion dependency {name!r} is not part of the extracted set",
                )
        else:
            raise _Refusal(
                "DEPENDENCY-PROVISION-INVALID",
                f"dependency {name!r} has unsupported provision {provision!r}",
            )
    if uncovered:
        raise _Refusal(
            "UNCOVERED-DEPENDENCY",
            "free variables not covered by the dependency manifest: " + ", ".join(uncovered),
        )
    for name in sorted(dep_map):
        if name not in free and str(dep_map[name].get("symbol", name)) not in extracted:
            if dep_map[name].get("provision") == "companion":
                continue  # companions may be declared defensively for the moved set
            outcome.diagnostics.append(
                Diagnostic(
                    "UNUSED-DEPENDENCY",
                    f"dependency {name!r} is declared but the extracted code does not use it",
                    None,
                    None,
                    "warning",
                )
            )


def _already_done_symbols(
    rule: Rule, ws, symbols: list[str], target_path: str
) -> RuleOutcome | None:
    source_path = str(rule.get("source_path"))
    if not ws.exists(source_path):
        return None
    text, _ = decode_source(ws.read(source_path), source_path)
    try:
        parsed = ParsedPython(source_path, text, "utf-8")
    except Exception:  # noqa: BLE001
        return None
    analysis = _SourceAnalysis(parsed)
    if any(s in analysis.top_level for s in symbols):
        return None
    if ws.exists(target_path):
        target_text, _ = decode_source(ws.read(target_path), target_path)
        if all(f"def {s}" in target_text or f"class {s}" in target_text for s in symbols):
            outcome = RuleOutcome(
                rule_id=rule.rule_id,
                kind=rule.kind,
                stage=rule.stage,
                status="already_done",
                expected_matches=rule.expected_matches,
            )
            return outcome
    return None


def apply_rule(rule: Rule, ctx: TransformContext) -> RuleOutcome:
    if rule.kind == "symbol_extract":
        return _apply_symbol_extract(rule, ctx)
    return _apply_class_member_extract(rule, ctx)


def _apply_symbol_extract(rule: Rule, ctx: TransformContext) -> RuleOutcome:
    ws = ctx.workspace
    source_path = str(rule.get("source_path"))
    source_sha = str(rule.get("source_sha256"))
    symbols = [str(s) for s in (rule.get("symbols") or [])]
    target_path = str(rule.get("target_path"))
    target_mode = str(rule.get("target_mode") or "create")
    dependencies = list(rule.get("dependencies") or [])
    registration = rule.get("registration") or None
    outcome = RuleOutcome(
        rule_id=rule.rule_id,
        kind=rule.kind,
        stage=rule.stage,
        status="refused",
        expected_matches=rule.expected_matches,
    )
    try:
        ctx.writable_strict(source_path)
        ctx.writable_strict(target_path)
    except Exception as exc:  # ToolError -> scope refusal
        outcome.diagnostics.append(
            Diagnostic("SCOPE-READ-ONLY", str(exc), None, None, ERROR)
        )
        return outcome
    try:
        done = _already_done_symbols(rule, ws, symbols, target_path)
        if done is not None:
            return done
        if not ws.exists(source_path):
            raise _Refusal("MISSING-INPUT", f"{source_path} does not exist")
        data = ws.read(source_path)
        actual = hashlib.sha256(data).hexdigest()
        if actual != source_sha:
            raise _Refusal(
                "INPUT-DRIFT",
                f"{source_path} sha256 {actual} does not match the pinned {source_sha}",
            )
        text, encoding = decode_source(data, source_path)
        parsed = ParsedPython(source_path, text, encoding)
        analysis = _SourceAnalysis(parsed)
        missing = [s for s in symbols if s not in analysis.top_level]
        if missing:
            raise _Refusal(
                "SYMBOL-NOT-FOUND",
                f"symbols missing in {source_path}: {', '.join(missing)}",
            )
        roots = [analysis.top_level[s] for s in symbols]
        extracted = set(symbols)

        wrapper_param = str(registration.get("parameter")) if registration else None
        dep_map: dict[str, dict] = {str(dep["name"]): dep for dep in dependencies}
        free = _free_variables(parsed, roots)
        free |= _annotation_string_names(parsed, roots)
        free -= extracted
        free -= {"__name__", "__file__", "__doc__", "__package__"}
        if wrapper_param:
            free.discard(wrapper_param)
        _check_dependencies(dep_map, free, extracted, registration, wrapper_param, ws, outcome)

        target_exists = ws.exists(target_path)
        if target_mode == "create" and target_exists:
            raise _Refusal("TARGET-CONFLICT", f"target {target_path} already exists")
        target_text = ""
        target_encoding = "utf-8"
        if target_mode == "append":
            if not target_exists:
                raise _Refusal("TARGET-MISSING", f"append target {target_path} does not exist")
            target_text, target_encoding = decode_source(ws.read(target_path), target_path)
            if GENERATED_NOTE not in target_text:
                raise _Refusal(
                    "TARGET-NOT-MANAGED",
                    f"{target_path} exists without the tool marker; refusing to append",
                )

        import_lines = _dep_import_lines(dep_map, sorted(free | {n for n in dep_map if dep_map[n].get("provision") == "import"}))
        moved_code = [
            _strip_trailing_newline(parsed.module.code_for_node(root)) for root in roots
        ]
        if registration:
            wrapper_name = str(registration.get("wrapper") or "register_commands")
            body = "\n\n".join(_indent(code) for code in moved_code)
            content = (
                f'"""{GENERATED_NOTE}: extracted symbols from {source_path}."""\n\n'
                + ("\n".join(import_lines) + "\n\n" if import_lines else "")
                + f"def {wrapper_name}({wrapper_param}):\n"
                + body
                + "\n"
            )
        else:
            content = (
                f'"""{GENERATED_NOTE}: extracted symbols {", ".join(symbols)} '
                f'from {source_path}."""\n\n'
                + ("\n".join(import_lines) + "\n\n" if import_lines else "")
                + "\n\n".join(moved_code)
                + "\n"
            )
        if target_mode == "create":
            ws.write(target_path, content.encode("utf-8"))
        else:
            ws.write(
                target_path,
                (target_text.rstrip("\n") + "\n\n\n" + "\n\n".join(moved_code) + "\n").encode(
                    target_encoding
                ),
            )

        removal_ids = {id(root) for root in roots}
        first_index = None
        for index, statement in enumerate(parsed.module.body):
            if id(statement) in removal_ids or (
                isinstance(statement, cst.SimpleStatementLine)
                and any(id(small) in removal_ids for small in statement.body)
            ):
                first_index = index
                break

        def rebuild(body: list[cst.CSTNode]) -> list[cst.CSTNode]:
            new_body: list[cst.CSTNode] = []
            call_inserted = False
            for statement in body:
                if id(statement) in removal_ids:
                    if first_index is not None and not call_inserted and registration:
                        call = cst.SimpleStatementLine(
                            body=[
                                cst.Expr(
                                    value=cst.Call(
                                        func=cst.Name(str(registration.get("wrapper") or "register_commands")),
                                        args=[cst.Arg(value=cst.Name(wrapper_param or "app"))],
                                    )
                                )
                            ]
                        )
                        new_body.append(call)
                        call_inserted = True
                    continue
                if isinstance(statement, cst.SimpleStatementLine) and any(
                    id(small) in removal_ids for small in statement.body
                ):
                    kept = [small for small in statement.body if id(small) not in removal_ids]
                    if not kept:
                        if registration and not call_inserted:
                            call = cst.SimpleStatementLine(
                                body=[
                                    cst.Expr(
                                        value=cst.Call(
                                            func=cst.Name(str(registration.get("wrapper") or "register_commands")),
                                            args=[cst.Arg(value=cst.Name(wrapper_param or "app"))],
                                        )
                                    )
                                ]
                            )
                            new_body.append(call)
                            call_inserted = True
                        continue
                    new_body.append(statement.with_changes(body=kept))
                    continue
                new_body.append(statement)
            return new_body

        new_module = parsed.module.with_changes(body=rebuild(list(parsed.module.body)))
        new_text = new_module.code
        # warn when code that STAYS behind still references the moved symbols
        removed = set(symbols)
        stale = sorted(
            {
                node.value
                for node in _walk(new_module)
                if isinstance(node, cst.Name) and node.value in removed
            }
        )
        if stale:
            outcome.diagnostics.append(
                Diagnostic(
                    "STALE-SOURCE-REFERENCE",
                    f"{source_path} still references moved symbols after extraction: "
                    + ", ".join(stale)
                    + "; pair with an import/facade rule",
                    source_path,
                    None,
                    "warning",
                )
            )
        if analysis.all_names & extracted:
            outcome.diagnostics.append(
                Diagnostic(
                    "STALE-ALL-EXPORT",
                    f"{source_path} __all__ lists moved symbols "
                    f"{sorted(analysis.all_names & extracted)}; pair with a facade rule",
                    source_path,
                    None,
                    "warning",
                )
            )
        ws.write(source_path, new_text.encode(encoding))
        outcome.status = "applied"
        outcome.matches = len(symbols)
        outcome.changed_paths = [source_path, target_path]
        outcome.detail["target_path"] = target_path
        return outcome
    except _Refusal as exc:
        outcome.diagnostics.append(
            Diagnostic(exc.code, exc.message, source_path, exc.line, ERROR)
        )
        return outcome


def _strip_trailing_newline(text: str) -> str:
    return text.rstrip("\n")


def _apply_class_member_extract(rule: Rule, ctx: TransformContext) -> RuleOutcome:
    ws = ctx.workspace
    source_path = str(rule.get("source_path"))
    source_sha = str(rule.get("source_sha256"))
    class_name = str(rule.get("class_name"))
    methods = [str(m) for m in (rule.get("symbols") or [])]
    new_class_name = str(rule.get("new_class_name"))
    target_path = str(rule.get("target_path"))
    host_attribute = str(rule.get("host_attribute") or "_collaborator")
    dependencies = list(rule.get("dependencies") or [])
    wiring = rule.get("wiring") or {}
    shim_methods = {str(s) for s in (rule.get("shim_methods") or [])}
    outcome = RuleOutcome(
        rule_id=rule.rule_id,
        kind=rule.kind,
        stage=rule.stage,
        status="refused",
        expected_matches=rule.expected_matches,
    )
    if not ws.exists(source_path):
        outcome.diagnostics.append(
            Diagnostic("MISSING-INPUT", f"{source_path} does not exist", source_path, None, ERROR)
        )
        return outcome
    try:
        ctx.writable_strict(source_path)
        ctx.writable_strict(target_path)
    except Exception as exc:  # ToolError -> scope refusal
        outcome.diagnostics.append(
            Diagnostic("SCOPE-READ-ONLY", str(exc), None, None, ERROR)
        )
        return outcome
    try:
        if not ws.exists(source_path):
            raise _Refusal("MISSING-INPUT", f"{source_path} does not exist")
        data = ws.read(source_path)
        actual = hashlib.sha256(data).hexdigest()
        if actual != source_sha:
            raise _Refusal("INPUT-DRIFT", f"{source_path} sha256 does not match the manifest pin")
        text, encoding = decode_source(data, source_path)
        parsed = ParsedPython(source_path, text, encoding)
        analysis = _SourceAnalysis(parsed)
        cls = analysis.classes.get(class_name)
        if cls is None:
            raise _Refusal("CLASS-NOT-FOUND", f"class {class_name!r} not found in {source_path}")
        method_nodes: dict[str, cst.CSTNode] = {}
        for statement in cls.body.body:
            if isinstance(statement, (cst.FunctionDef)):
                method_nodes[statement.name.value] = statement
        missing = [m for m in methods if m not in method_nodes]
        if missing:
            raise _Refusal(
                "SYMBOL-NOT-FOUND",
                f"methods missing on {class_name}: {', '.join(missing)}",
            )
        moved_set = set(methods)
        dep_map: dict[str, dict] = {str(dep["name"]): dep for dep in dependencies}

        fields: list[str] = []
        host_refs: set[str] = set()
        class_attr_refs: set[str] = set()
        for method_name in methods:
            node = method_nodes[method_name]
            for sub in _walk(node):
                if (
                    isinstance(sub, cst.Call)
                    and isinstance(sub.func, cst.Name)
                    and sub.func.value == "super"
                    and not sub.args
                ):
                    raise _Refusal(
                        "SUPER-CELL-UNSUPPORTED",
                        f"method {method_name!r} uses zero-arg super(); extracting it changes "
                        "the __class__ cell and needs an explicit rule",
                        parsed.line_of(sub),
                    )
                if (
                    isinstance(sub, cst.Attribute)
                    and isinstance(sub.value, cst.Name)
                    and sub.value.value == "self"
                ):
                    attr = sub.attr.value
                    if attr in moved_set:
                        continue
                    dep = dep_map.get(f"self.{attr}")
                    if dep is None:
                        raise _Refusal(
                            "UNCOVERED-SELF-ATTRIBUTE",
                            f"self.{attr} used by {method_name!r} is not classified in the "
                            "dependency manifest",
                            parsed.line_of(sub),
                        )
                    provision = dep.get("provision")
                    if provision == "field":
                        if attr not in fields:
                            fields.append(attr)
                    elif provision == "host":
                        host_refs.add(attr)
                    elif provision == "class_attr":
                        class_attr_refs.add(attr)
                    else:
                        raise _Refusal(
                            "DEPENDENCY-PROVISION-INVALID",
                            f"self.{attr} provision {provision!r} unsupported",
                            parsed.line_of(sub),
                        )
        for attr in class_attr_refs:
            dep = dep_map[f"self.{attr}"]
            if not dep.get("class") or not dep.get("module"):
                raise _Refusal(
                    "DEPENDENCY-PROVISION-INVALID",
                    f"self.{attr} class_attr provision requires module and class",
                )

        free = _free_variables(parsed, [method_nodes[m] for m in methods])
        free |= _annotation_string_names(parsed, [method_nodes[m] for m in methods])
        free -= moved_set
        free -= {"__name__", "__file__", "__doc__", "__package__"}
        for name in sorted(free):
            dep = dep_map.get(name)
            if dep is None or dep.get("provision") != "import":
                raise _Refusal(
                    "UNCOVERED-DEPENDENCY",
                    f"free variable {name!r} must be declared with provision 'import'",
                )
            module = dep.get("module")
            if not module or not _dependency_module_known(ws, str(module)):
                raise _Refusal(
                    "DEPENDENCY-MODULE-UNKNOWN",
                    f"dependency {name!r} imports from unknown module {module!r}",
                )

        if not wiring or "method" not in wiring or "code" not in wiring:
            raise _Refusal(
                "WIRING-REQUIRED",
                "class_member_extract requires trusted wiring {method, code} in the manifest",
            )
        wiring_method = str(wiring["method"])
        wiring_code = str(wiring["code"])
        try:
            wiring_stmts = [cst.parse_statement(wiring_code)]
        except Exception as exc:  # noqa: BLE001
            raise _Refusal("WIRING-CODE-INVALID", f"wiring code does not parse: {exc}")
        host_method_names = {
            statement.name.value
            for statement in cls.body.body
            if isinstance(statement, (cst.FunctionDef))
        }
        if wiring_method not in host_method_names:
            raise _Refusal(
                "WIRING-METHOD-MISSING",
                f"wiring method {wiring_method!r} not found on {class_name}",
            )

        remaining_calls: set[str] = set()
        moved_ids = {id(method_nodes[m]) for m in methods}
        for statement in cls.body.body:
            if id(statement) in moved_ids:
                continue
            for sub in _walk(statement):
                if (
                    isinstance(sub, cst.Call)
                    and isinstance(sub.func, cst.Attribute)
                    and isinstance(sub.func.value, cst.Name)
                    and sub.func.value.value == "self"
                    and sub.func.attr.value in moved_set
                ):
                    remaining_calls.add(sub.func.attr.value)
        shims = sorted(remaining_calls | shim_methods)

        import_lines = _dep_import_lines(dep_map, sorted(free))
        for attr in sorted(class_attr_refs):
            dep = dep_map[f"self.{attr}"]
            import_lines.append(f"from {dep['module']} import {dep['class']}")
        import_lines = sorted(set(import_lines))

        init_params = ["self", "host", *fields]
        init_lines = ["        self.host = host"] + [
            f"        self.{attr} = {attr}" for attr in fields
        ]
        ctor = (
            f"    def __init__({', '.join(init_params)}):\n" + "\n".join(init_lines) + "\n"
        )
        moved_bodies = []
        for method_name in methods:
            node = method_nodes[method_name]
            code = _rewrite_self_refs(
                parsed.module.code_for_node(node), host_refs, class_attr_refs, dep_map
            )
            moved_bodies.append(_strip_trailing_newline(code))
        collaborator = (
            f'"""{GENERATED_NOTE}: collaborator extracted from {class_name} '
            f'in {source_path}."""\n\n'
            + ("\n".join(import_lines) + "\n\n" if import_lines else "")
            + f"class {new_class_name}:\n"
            + ctor
            + "\n\n"
            + "\n\n".join(moved_bodies)
            + "\n"
        )
        if ws.exists(target_path):
            raise _Refusal("TARGET-CONFLICT", f"target {target_path} already exists")
        ws.write(target_path, collaborator.encode("utf-8"))

        shim_codes = [_render_shim(method_nodes[m], host_attribute) for m in shims]

        wiring_imports = [str(line) for line in (wiring.get("imports") or [])]
        import_stmts = []
        for line in wiring_imports:
            try:
                import_stmts.append(cst.parse_statement(line))
            except Exception as exc:  # noqa: BLE001
                raise _Refusal("WIRING-CODE-INVALID", f"wiring import does not parse: {exc}")

        def rebuild(body: list[cst.CSTNode]) -> list[cst.CSTNode]:
            new_body: list[cst.CSTNode] = list(import_stmts)
            for statement in body:
                if isinstance(statement, cst.ClassDef) and statement.name.value == class_name:
                    new_body.append(_rebuild_class(statement, moved_ids, wiring_method, wiring_stmts, shim_codes))
                else:
                    new_body.append(statement)
            return new_body

        new_module = parsed.module.with_changes(body=rebuild(list(parsed.module.body)))
        ws.write(source_path, new_module.code.encode(encoding))
        outcome.status = "applied"
        outcome.matches = len(methods)
        outcome.changed_paths = [source_path, target_path]
        outcome.detail["shims"] = shims
        return outcome
    except _Refusal as exc:
        outcome.diagnostics.append(
            Diagnostic(exc.code, exc.message, source_path, exc.line, ERROR)
        )
        return outcome


def _rebuild_class(
    cls: cst.ClassDef,
    moved_ids: set[int],
    wiring_method: str,
    wiring_stmts: list[cst.CSTNode],
    shim_codes: list[str],
) -> cst.ClassDef:
    new_body: list[cst.CSTNode] = []
    for statement in cls.body.body:
        if id(statement) in moved_ids:
            continue
        if isinstance(statement, (cst.FunctionDef)) and (
            statement.name.value == wiring_method
        ):
            inner = list(statement.body.body) + list(wiring_stmts)
            new_body.append(
                statement.with_changes(body=statement.body.with_changes(body=inner))
            )
            continue
        new_body.append(statement)
    for shim in shim_codes:
        new_body.append(cst.parse_statement(shim))
    return cls.with_changes(body=cls.body.with_changes(body=new_body))


def _rewrite_self_refs(
    code: str, host_refs: set[str], class_attr_refs: set[str], dep_map: dict
) -> str:
    module = cst.parse_module(code)

    class SelfRewriter(cst.CSTTransformer):
        def leave_Attribute(self, original_node, updated_node):
            value = original_node.value
            if isinstance(value, cst.Name) and value.value == "self":
                attr = original_node.attr.value
                if attr in host_refs:
                    return updated_node.with_changes(
                        value=cst.Attribute(value=cst.Name("self"), attr=cst.Name("host"))
                    )
                if attr in class_attr_refs:
                    class_name = dep_map[f"self.{attr}"].get("class")
                    return updated_node.with_changes(value=cst.Name(str(class_name)))
            return updated_node

    return module.visit(SelfRewriter()).code


